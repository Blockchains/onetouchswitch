import { test, expect } from "@playwright/test";
test("postcode -> caveats -> address -> current deal -> published offers + quote -> deterministic results -> saved session", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("Your postcode").fill("hu1 1aa");
  await page.getByRole("button", { name: "Find my area" }).click();
  await expect(page.getByTestId("area")).toContainText("City of Kingston upon Hull");
  await expect(page.locator('[data-caveat="kcom-area"]')).toBeVisible();
  await expect(page.locator('[data-caveat="availability"]')).toContainText("Check availability at your exact address with the provider");
  await page.getByLabel("Address line 1").fill("1  high   street");
  await page.getByLabel("Town").fill("hull");
  await page.getByRole("button", { name: "Use this address" }).click();
  await expect(page.getByTestId("address-result")).toContainText("1 High Street, HULL, HU1 1AA");
  await expect(page.getByTestId("address-result")).toContainText("not verified");
  await page.getByLabel("Monthly price now (£)").fill("25.00");
  await page.getByLabel("Price after contract ends (£)").fill("45.00");
  const offers = page.getByTestId("offers");
  await expect(offers.locator("li")).toHaveCount(2);
  await expect(offers).toContainText("Published offer. Check availability with the provider.");
  for (const cb of await offers.getByRole("checkbox").all()) await cb.check();
  await page.getByLabel("Provider / deal").fill("Quote from a shop");
  await page.getByLabel("Monthly (£)").fill("22");
  await page.getByRole("button", { name: "Add quote" }).click();
  await page.getByRole("button", { name: "Compare total cost" }).click();
  const results = page.getByTestId("results");
  await expect(results.locator("tbody tr")).toHaveCount(3);
  // 24 months: quote 22*24 = £528.00; fixture A 6x30 + 12x33 + 6x36 = £792.00; fixture B 25*24 + 29.99 = £629.99 (horizon = longest contract)
  await expect(results.locator("tbody tr").nth(0)).toContainText("£528.00");
  await expect(results.locator("tbody tr").nth(1)).toContainText("£629.99");
  await expect(results.locator("tbody tr").nth(2)).toContainText("£792.00");
  await expect(results).toContainText("not deducted");
  await expect(page.getByTestId("stay")).toContainText("£1080.00");
  await expect(results.getByRole("link", { name: /Check availability with BT/ })).toHaveAttribute("href", /bt\.com/);
  await page.getByRole("button", { name: "Save this comparison" }).click();
  await expect(page.getByTestId("session")).toContainText(/[0-9a-f-]{36}/);
});
